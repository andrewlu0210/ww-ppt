//! Autosave for crash recovery: the frontend periodically writes the open
//! document to `~/Library/Application Support/<app>/Recovery/<id>.pptx` with
//! a `<id>.json` describing it, and removes both once the document is saved or
//! discarded. Copies left behind by an instance that is no longer running are
//! offered for recovery at the next launch.

use std::path::PathBuf;

use serde::{Deserialize, Serialize};
use tauri::ipc::{InvokeBody, Request, Response};
use tauri::{AppHandle, Manager};

#[derive(Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct RecoveryInfo {
    pub id: String,
    /// Document name shown to the user.
    pub name: String,
    /// Where the document was opened from or last saved, if anywhere.
    pub path: Option<String>,
    /// Milliseconds since the Unix epoch.
    pub saved_at: u64,
    /// The process that wrote it: copies of running instances are not offered.
    pub pid: u32,
}

fn dir(app: &AppHandle) -> Result<PathBuf, String> {
    let dir = app.path().app_data_dir().map_err(|e| e.to_string())?.join("Recovery");
    std::fs::create_dir_all(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    Ok(dir)
}

/// Ids are generated by the frontend; keep them to safe file names.
fn safe(id: &str) -> Result<&str, String> {
    if !id.is_empty() && id.len() <= 64 && id.chars().all(|c| c.is_ascii_alphanumeric() || c == '-') { Ok(id) } else { Err("bad recovery id".into()) }
}

fn alive(pid: u32) -> bool {
    // Signal 0 only checks that the process exists.
    pid != 0 && unsafe { libc::kill(pid as libc::pid_t, 0) == 0 }
}

fn header<'a>(request: &'a Request<'_>, name: &str) -> Option<&'a str> {
    request.headers().get(name).and_then(|v| v.to_str().ok())
}

/// Writes the recovery copy. Headers: `id`, `name` and `path` (percent-encoded); body: PPTX bytes.
#[tauri::command]
pub fn recovery_write(app: AppHandle, request: Request<'_>) -> Result<(), String> {
    let id = safe(header(&request, "id").ok_or("missing id")?)?.to_string();
    let name = crate::percent_decode(header(&request, "name").unwrap_or(""));
    let path = header(&request, "path").map(crate::percent_decode).filter(|p| !p.is_empty());
    let InvokeBody::Raw(bytes) = request.body() else { return Err("expected raw body".into()) };
    let dir = dir(&app)?;
    // Write then rename, so a crash mid-write leaves the previous copy intact.
    let file = dir.join(format!("{id}.pptx"));
    let tmp = dir.join(format!("{id}.pptx.tmp"));
    std::fs::write(&tmp, bytes).map_err(|e| e.to_string())?;
    std::fs::rename(&tmp, &file).map_err(|e| e.to_string())?;
    let saved_at = std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).map_or(0, |d| d.as_millis() as u64);
    let info = RecoveryInfo { id: id.clone(), name, path, saved_at, pid: std::process::id() };
    let json = serde_json::to_vec(&info).map_err(|e| e.to_string())?;
    std::fs::write(dir.join(format!("{id}.json")), json).map_err(|e| e.to_string())
}

#[tauri::command]
pub fn recovery_clear(app: AppHandle, id: String) -> Result<(), String> {
    let id = safe(&id)?;
    let dir = dir(&app)?;
    for ext in ["pptx", "json", "pptx.tmp"] {
        let _ = std::fs::remove_file(dir.join(format!("{id}.{ext}")));
    }
    Ok(())
}

/// Copies left by instances that are no longer running, newest first.
#[tauri::command]
pub fn recovery_list(app: AppHandle) -> Result<Vec<RecoveryInfo>, String> {
    let dir = dir(&app)?;
    let mut out: Vec<RecoveryInfo> = std::fs::read_dir(&dir)
        .map_err(|e| e.to_string())?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|x| x == "json"))
        .filter_map(|p| serde_json::from_slice::<RecoveryInfo>(&std::fs::read(&p).ok()?).ok())
        .filter(|i| safe(&i.id).is_ok() && dir.join(format!("{}.pptx", i.id)).exists())
        .filter(|i| i.pid == std::process::id() || !alive(i.pid))
        .collect();
    out.sort_by_key(|i| std::cmp::Reverse(i.saved_at));
    Ok(out)
}

#[tauri::command]
pub fn recovery_read(app: AppHandle, id: String) -> Result<Response, String> {
    let id = safe(&id)?;
    std::fs::read(dir(&app)?.join(format!("{id}.pptx"))).map(Response::new).map_err(|e| e.to_string())
}
